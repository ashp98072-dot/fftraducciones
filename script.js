const storedLang = localStorage.getItem("ff-lang");
let currentLang = storedLang === "en" || storedLang === "es" ? storedLang : "es";

const langToggle = document.getElementById("langToggle");
const langLabel = document.getElementById("langLabel");
const menuBtn = document.getElementById("menuBtn");
const nav = document.getElementById("nav");
const header = document.querySelector(".site-header");
const form = document.getElementById("quoteForm");
const formNote = document.getElementById("formNote");

function applyTranslations(lang) {
  const dict = translations[lang];
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] != null) {
      el.textContent = dict[key];
    }
  });

  langLabel.textContent = lang === "es" ? "EN" : "ES";
  const title = pageTitle[document.body.dataset.page]?.[lang];
  if (title) {
    document.title = title;
    document.querySelectorAll("[data-page-title]").forEach((el) => {
      el.setAttribute("content", title);
    });
  }

  document.querySelectorAll("[data-i18n-content]").forEach((el) => {
    const text = dict[el.getAttribute("data-i18n-content")];
    if (text != null) el.setAttribute("content", text);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    const text = dict[el.getAttribute("data-i18n-aria-label")];
    if (text != null) el.setAttribute("aria-label", text);
  });
  localStorage.setItem("ff-lang", lang);
}

langToggle.addEventListener("click", () => {
  currentLang = currentLang === "es" ? "en" : "es";
  applyTranslations(currentLang);
});

menuBtn.addEventListener("click", () => {
  const open = nav.classList.toggle("is-open");
  menuBtn.setAttribute("aria-expanded", String(open));
});

const navLinks = Array.from(nav.querySelectorAll("a"));

navLinks.forEach((link) => {
  link.addEventListener("click", () => {
    nav.classList.remove("is-open");
    menuBtn.setAttribute("aria-expanded", "false");
  });
});

window.addEventListener("scroll", () => {
  header.classList.toggle("is-scrolled", window.scrollY > 8);
});

// Highlight the matching nav link as each section scrolls into view.
const sectionIds = navLinks
  .map((link) => link.getAttribute("href"))
  .filter((href) => href && href.startsWith("#"));

const sections = sectionIds
  .map((id) => document.querySelector(id))
  .filter(Boolean);

if (sections.length && "IntersectionObserver" in window) {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        const id = `#${entry.target.id}`;
        navLinks.forEach((link) => {
          link.classList.toggle("is-active", link.getAttribute("href") === id);
        });
      });
    },
    { rootMargin: "-45% 0px -50% 0px", threshold: 0 }
  );
  sections.forEach((section) => observer.observe(section));
}

if (form) {
  const submitBtn = form.querySelector('button[type="submit"]');

  form.addEventListener("submit", (e) => {
    e.preventDefault();
    if (submitBtn?.disabled) return;
    if (!form.checkValidity()) {
      form.reportValidity();
      return;
    }

    formNote.classList.remove("is-success", "is-error");
    formNote.textContent = translations[currentLang]["form.sending"];
    if (submitBtn) submitBtn.disabled = true;

    fetch(form.action, {
      method: "POST",
      body: new URLSearchParams(new FormData(form)),
      headers: { Accept: "application/json" },
    })
      .then((response) => {
        if (response.ok) {
          formNote.textContent = translations[currentLang]["form.success"];
          formNote.classList.add("is-success");
          form.reset();
        } else {
          formNote.textContent = translations[currentLang]["form.error"];
          formNote.classList.add("is-error");
        }
      })
      .catch(() => {
        formNote.textContent = translations[currentLang]["form.error"];
        formNote.classList.add("is-error");
      })
      .finally(() => {
        if (submitBtn) submitBtn.disabled = false;
      });
  });
}

applyTranslations(currentLang);
